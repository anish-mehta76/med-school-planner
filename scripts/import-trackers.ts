/**
 * Turns the research tracker CSVs in the repo root into typed data modules.
 *
 *   npm run import-trackers
 *
 * Re-run after editing either CSV. Only PUBLIC columns are written (names,
 * institutions, public profiles and papers), because src/data is bundled into
 * the website. Your pitches, draft emails and outreach columns are never
 * written here: the app reads them in the browser via "Import tracker CSV".
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import Papa from 'papaparse';
import { parseCited, parseEmail, parseProgramDates, parsePublications } from './parse.ts';
import type { Mentor, MentorPriority, Program } from '../src/types.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function readCsv(file: string): Record<string, string>[] {
  const text = readFileSync(join(root, file), 'utf8').replace(/^﻿/, '');
  const { data, errors } = Papa.parse<Record<string, string>>(text, { header: true, skipEmptyLines: true });
  if (errors.length) throw new Error(`${file}: ${errors.map((e) => `row ${e.row}: ${e.message}`).join('; ')}`);
  return data;
}

function importMentors(): Mentor[] {
  return readCsv('uterine-cervical-cancer-opportunities-tracker.csv').map((r) => {
    const contact = parseCited(r['Public contact or route']);
    return {
      id: r.ID.trim(),
      priority: r['Outreach priority'].trim() as MentorPriority,
      name: r.Researcher.trim(),
      institution: parseCited(r['Institution and location']),
      diseaseFit: parseCited(r['Disease fit']),
      strength: parseCited(r['Distinctive research strength']),
      publications: parsePublications(r['Verified publication examples']),
      contact,
      email: parseEmail(r['Public contact or route']),
      evidenceGate: r['Publication evidence gate'].trim(),
      lastVerified: r['Last research verification date'].trim(),
      undergradOpening: parseCited(r['Current lab-specific undergraduate opening']),
      mentorshipEvidence: parseCited(r['Lab-specific undergraduate mentorship evidence']),
      evidenceUrl: r['Primary personalization evidence URL']?.trim() || undefined,
    };
  });
}

function importPrograms(today: string): Program[] {
  return readCsv('new_york_cancer_research_tracker.csv').map((r) => {
    const timeline = r['Application timeline'].trim();
    const { dates, deadline, deadlineVerified } = parseProgramDates(timeline, today);
    return {
      id: `NYC${r.Priority.trim().padStart(2, '0')}`,
      priority: Number(r.Priority),
      name: r.Opportunity.trim(),
      location: r.Location.trim(),
      recommendation: r['Recommendation/status'].trim(),
      eligibility: r.Eligibility.trim(),
      timeline,
      deadline,
      deadlineVerified,
      dates,
      summerDates: r['Summer dates'].trim(),
      fit: r['Research fit'].trim(),
      publicationEvidence: r['Publication evidence'].trim(),
      deliverable: r['Final deliverable'].trim(),
      pay: r['Pay/housing'].trim(),
      nextAction: r['Next action'].trim(),
      source: r['Official source'].trim(),
    };
  });
}

function write(file: string, header: string, name: string, type: string, data: unknown) {
  const body = `// Generated by scripts/import-trackers.ts — edit the CSV and re-run instead of editing this file.\n${header}\nexport const ${name}: ${type}[] = ${JSON.stringify(data, null, 2)};\n`;
  mkdirSync(join(root, 'src/data/private'), { recursive: true });
  writeFileSync(join(root, 'src/data/private', file), body);
}

const now = new Date();
const today = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
const mentors = importMentors();
const programs = importPrograms(today);
write('mentors.ts', "import type { Mentor } from '../../types';\n", 'MENTORS', 'Mentor', mentors);
write('nycPrograms.ts', "import type { Program } from '../../types';\n", 'NYC_PROGRAMS', 'Program', programs);
console.log(`Imported ${mentors.length} mentors and ${programs.length} programs.`);
